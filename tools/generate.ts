import { STROKE_WEIGHTS } from '@squircle-icons/core/source/types';
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { root } from './paths.js';
import { componentNames } from './icon-names.js';
import { fileURLToPath } from 'node:url';
import type { CoreIcon } from '@squircle-icons/core/catalog-types';
type SvgNode = CoreIcon['root'];

const check = process.argv.includes('--check');
const header = '// Generated by tools/generate.ts. Do not edit.\n';
const files = new Map<string, string>();
const icons: CoreIcon[] = JSON.parse(
  await readFile(fileURLToPath(import.meta.resolve('@squircle-icons/core/catalog.json')), 'utf8'),
);
const names = componentNames(icons.map((icon) => icon.name));
const render = (node: SvgNode): string => {
  const attrs = Object.entries(node.attrs)
    .map(([key, value]) => `${key}=${JSON.stringify(value)}`)
    .join(' ');
  return `<${node.tag}${attrs ? ' ' + attrs : ''}>${node.children.map(render).join('')}</${node.tag}>`;
};
const rootAttrs = `xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width={size} height={size} fill="none" stroke={color} stroke-width={resolvedStrokeWidth} stroke-linecap="round" stroke-linejoin="round" class={className} role={accessibleLabel ? 'img' : undefined} aria-label={accessibleLabel || undefined} aria-hidden={accessibleLabel ? undefined : true} focusable="false"`;
const baseProps = `size = 24, color = 'currentColor', strokeWidth = 'regular', label, class: className`;
const exports: Record<string, unknown> = {
  '.': { types: './dist/index.d.ts', svelte: './dist/index.js', default: './dist/index.js' },
};
let staticIndex =
  header + "export type { IconProps, IconStyle, IconStrokeWidth, IconFrame } from './props.js';\n";
let filledIndex = header + "export type { FilledIconProps } from '../props.js';\n";
const filledRootAttrs = rootAttrs.replace(
  'fill="none" stroke={color} stroke-width={resolvedStrokeWidth}',
  'fill={color} stroke="none" fill-rule="evenodd"',
);
for (const [index, icon] of icons.entries()) {
  const component = names[index];
  const withFrame = (style: 'outline' | 'filled', fallback: string) => {
    if (!icon.frames) return fallback;
    const source = (name: 'square' | 'circle') => {
      const variant = icon.frames![name]!;
      return (style === 'outline' ? variant.root : variant.filled.root).children
        .map(render)
        .join('\n');
    };
    return `{#if frame === 'square'}${source('square')}{:else if frame === 'circle'}${source('circle')}{:else}${fallback}{/if}`;
  };
  const frameProp = icon.frames ? ", frame = 'none'" : '';
  const frameAttrs = icon.frames ? ' data-frame={frame}' : '';
  const plainBody = icon.root.children.map((child) => render(child)).join('\n  ');
  const body = withFrame('outline', plainBody);
  staticIndex += `export { default as ${component} } from './${component}.svelte';\n`;
  exports[`./${icon.name}`] = {
    types: `./dist/${component}.svelte.d.ts`,
    svelte: `./dist/${component}.svelte`,
    default: `./dist/${component}.svelte`,
  };
  const cutout = icon.filled?.cutout;
  const gapScript = cutout
    ? `
  const gapWidth = $derived(Number.isFinite(resolvedStrokeWidth) ? Math.min(${cutout.maxWidth}, Math.max(${cutout.minWidth}, resolvedStrokeWidth)) : ${cutout.defaultWidth});
  const cutoutPath = $derived(${JSON.stringify(cutout.outerPath)} + ' M ${cutout.left} ' + (${cutout.centerY} - gapWidth / 2) + ' H ${cutout.right} V ' + (${cutout.centerY} + gapWidth / 2) + ' H ${cutout.left} Z');`
    : '';
  const plainFilledBody =
    icon.filled?.root.children
      .map((node) =>
        cutout && node.attrs['data-part'] === cutout.part
          ? `<g data-part=${JSON.stringify(cutout.part)}><path d={cutoutPath}></path></g>`
          : render(node),
      )
      .join('\n  ') ?? '';
  const filledBody = withFrame('filled', plainFilledBody);
  if (icon.filled) {
    files.set(
      `src/lib/filled/${component}.svelte`,
      `<!-- Generated by tools/generate.ts. Do not edit. -->
<script lang="ts">
  import type { FilledIconProps } from '../props.js';${cutout ? "\n  import { resolveStrokeWidth } from '../stroke-width.js';" : ''}
  let { size = 24, color = 'currentColor', strokeWidth = 'regular', label, class: className${frameProp} }: FilledIconProps = $props();
  const accessibleLabel = $derived(label?.trim());${cutout ? '\n  const resolvedStrokeWidth = $derived(resolveStrokeWidth(strokeWidth));' : ''}${gapScript}
</script>
<svg ${filledRootAttrs}${frameAttrs}${cutout ? ' data-cutout-width={gapWidth}' : ''}>
  ${filledBody}
</svg>\n`,
    );
    filledIndex += `export { default as ${component} } from './${component}.svelte';\n`;
    exports[`./filled/${icon.name}`] = {
      types: `./dist/filled/${component}.svelte.d.ts`,
      svelte: `./dist/filled/${component}.svelte`,
      default: `./dist/filled/${component}.svelte`,
    };
  }
  const variantAttrs = icon.filled
    ? rootAttrs.replace(
        'fill="none" stroke={color} stroke-width={resolvedStrokeWidth}',
        `fill={iconStyle === 'filled' ? color : 'none'} stroke={iconStyle === 'filled' ? 'none' : color} stroke-width={iconStyle === 'filled' ? undefined : resolvedStrokeWidth} fill-rule={iconStyle === 'filled' ? 'evenodd' : undefined}`,
      )
    : rootAttrs;
  files.set(
    `src/lib/${component}.svelte`,
    `<!-- Generated by tools/generate.ts. Do not edit. -->
<script lang="ts">
  import type { IconProps } from './props.js';
  import { resolveStrokeWidth } from './stroke-width.js';
  let { ${baseProps}${frameProp}, style: iconStyle = 'outline' }: ${icon.filled ? 'IconProps' : "Omit<IconProps, 'style'> & { style?: 'outline' }"} = $props();
  const accessibleLabel = $derived(label?.trim());
  const resolvedStrokeWidth = $derived(iconStyle === 'bold' ? ${STROKE_WEIGHTS.bold} : resolveStrokeWidth(strokeWidth));${gapScript}
</script>
<svg ${variantAttrs}${icon.frames ? " data-frame={iconStyle === 'bold' ? 'none' : frame}" : ''}${cutout ? " data-cutout-width={iconStyle === 'filled' ? gapWidth : undefined}" : ''}>
  ${icon.filled ? `{#if iconStyle === 'filled'}\n${filledBody}\n{:else if iconStyle === 'bold'}\n${plainBody}\n{:else}\n${body}\n{/if}` : body}
</svg>
`,
  );
}
files.set(
  'src/lib/stroke-width.ts',
  header +
    `import type { IconStrokeWidth } from './props.js';
const weights = ${JSON.stringify(STROKE_WEIGHTS)} as const;
export function resolveStrokeWidth(value: IconStrokeWidth): number {
  if (typeof value === 'number' && Number.isFinite(value) && value >= 0) return value;
  return value === 'thin' ? weights.thin : value === 'bold' ? weights.bold : weights.regular;
}
`,
);
files.set('src/lib/index.ts', staticIndex);
files.set('src/lib/filled/index.ts', filledIndex);
exports['./filled'] = {
  types: './dist/filled/index.d.ts',
  svelte: './dist/filled/index.js',
  default: './dist/filled/index.js',
};
files.set(
  'src/lib/catalog.json',
  JSON.stringify(
    {
      generatedBy: 'tools/generate.ts',
      strokeWeights: STROKE_WEIGHTS,
      icons: icons.map((icon) => ({
        ...icon.metadata,
        styles: icon.metadata.supportsBold
          ? ['outline', 'bold', 'filled']
          : icon.filled
            ? ['outline', 'filled']
            : ['outline'],
        frames: icon.frames ? Object.keys(icon.frames) : [],
        defaultStrokeWidth: Number(icon.root.attrs['stroke-width']),
        filledDefaultStrokeWidth: icon.filled?.cutout?.defaultWidth ?? null,
        reviewStatus: icon.metadata.review?.status ?? 'draft',
      })),
    },
    null,
    2,
  ) + '\n',
);
exports['./catalog.json'] = './dist/catalog.json';
// Preserve relative imports for shared pure geometry used by opt-in morphs.
const strokes = fileURLToPath(import.meta.resolve('@squircle-icons/core/morph/round-strokes'));
files.set('src/lib/morph/round-strokes.js', header + (await readFile(strokes, 'utf8')));
files.set(
  'src/lib/morph/round-strokes.d.ts',
  header + (await readFile(strokes.replace(/\.js$/, '.d.ts'), 'utf8')),
);
// Pair implementations stay opt-in; static imports never traverse these modules.
for (const [pair, component, type] of [
  ['sun-moon', 'SunMoonMorph', 'SunMoonGeometry'],
  ['plus-x', 'PlusXMorph', 'PlusXGeometry'],
  ['menu-x', 'MenuXMorph', 'MenuXGeometry'],
  ['plus-minus', 'PlusMinusMorph', 'PlusMinusGeometry'],
]) {
  exports[`./morph/${pair}`] = {
    types: `./dist/morph/${component}.svelte.d.ts`,
    svelte: `./dist/morph/${component}.svelte`,
    default: `./dist/morph/${component}.svelte`,
  };
  const implementation = fileURLToPath(import.meta.resolve(`@squircle-icons/core/morph/${pair}`));
  files.set(`src/lib/morph/${pair}-geometry.js`, header + (await readFile(implementation, 'utf8')));
  files.set(
    `src/lib/morph/${pair}-geometry.d.ts`,
    header + (await readFile(implementation.replace(/\.js$/, '.d.ts'), 'utf8')),
  );
  files.set(
    `src/lib/morph/${pair}-data.js`,
    header +
      'export default ' +
      (await readFile(
        fileURLToPath(import.meta.resolve(`@squircle-icons/core/morph/${pair}.json`)),
        'utf8',
      )) +
      ';\n',
  );
  files.set(
    `src/lib/morph/${pair}-data.d.ts`,
    header +
      `import type { ${type} } from './${pair}-geometry.js';\ndeclare const geometry: ${type};\nexport default geometry;\n`,
  );
}
const packagePath = 'package.json';
const manifest = JSON.parse(await readFile(resolve(root, packagePath), 'utf8'));
manifest.exports = exports;
files.set(packagePath, JSON.stringify(manifest, null, 2) + '\n');
const formatting = await resolveConfig(resolve(root, '.prettierrc.json'));
for (const [path, source] of files) {
  const destination = resolve(root, path);
  const content = await format(source, { ...formatting, filepath: destination });
  if (check) {
    if ((await readFile(destination, 'utf8').catch(() => '')) !== content)
      throw new Error(`Generated output is stale: ${path}`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
// Removed icons must not leave stale, importable generated components behind.
async function scan(directory: string): Promise<string[]> {
  const entries = await readdir(resolve(root, directory), { withFileTypes: true }).catch(() => []);
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory() ? scan(`${directory}/${entry.name}`) : [`${directory}/${entry.name}`],
      ),
    )
  ).flat();
}
for (const path of await scan('src/lib')) {
  const content = await readFile(resolve(root, path), 'utf8');
  if (content.includes('Generated by tools/generate.ts.') && !files.has(path))
    throw new Error(`Stale generated file: ${path}; remove it explicitly`);
}
console.log(`${check ? 'Verified' : 'Generated'} ${files.size} deterministic outputs.`);
