import { STROKE_WEIGHTS } from '@squircle-icons/core/source/types';
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { root } from './paths.js';
import { fileURLToPath } from 'node:url';
import type { CoreIcon } from '@squircle-icons/core/catalog-types';
type SvgNode = CoreIcon['root'];

const check = process.argv.includes('--check');
const header = '// Generated by tools/generate.ts. Do not edit.\n';
const files = new Map<string, string>();
const icons: CoreIcon[] = JSON.parse(
  await readFile(fileURLToPath(import.meta.resolve('@squircle-icons/core/catalog.json')), 'utf8'),
);
const pascal = (name: string) =>
  name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
const render = (node: SvgNode): string => {
  const attrs = Object.entries(node.attrs)
    .map(([key, value]) => `${key}=${JSON.stringify(value)}`)
    .join(' ');
  return `<${node.tag}${attrs ? ' ' + attrs : ''}>${node.children.map(render).join('')}</${node.tag}>`;
};
const rootAttrs = `xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width={size} height={size} fill="none" stroke={color} stroke-width={strokeWidth} stroke-linecap="round" stroke-linejoin="round" class={className} role={label ? 'img' : undefined} aria-label={label || undefined} aria-hidden={label ? undefined : true} focusable="false"`;
const baseProps = `size = 24, color = 'currentColor', strokeWidth = 1.75, label, class: className`;
const exports: Record<string, unknown> = {
  '.': { types: './dist/index.d.ts', svelte: './dist/index.js', default: './dist/index.js' },
};
let staticIndex = header + "export type { IconProps, IconStyle } from './props.js';\n";
let filledIndex = header + "export type { FilledIconProps } from '../props.js';\n";
const filledRootAttrs = rootAttrs.replace(
  'fill="none" stroke={color} stroke-width={strokeWidth}',
  'fill={color} stroke="none" fill-rule="evenodd"',
);
for (const icon of icons) {
  const component = pascal(icon.name);
  const iconProps = baseProps.replace(
    'strokeWidth = 1.75',
    `strokeWidth = ${Number(icon.root.attrs['stroke-width'])}`,
  );
  const body = icon.root.children.map((child) => render(child)).join('\n  ');
  staticIndex += `export { default as ${component} } from './${component}.svelte';\n`;
  exports[`./${icon.name}`] = {
    types: `./dist/${component}.svelte.d.ts`,
    svelte: `./dist/${component}.svelte`,
    default: `./dist/${component}.svelte`,
  };
  const cutout = icon.filled?.cutout;
  const gapScript = cutout
    ? `
  const gapWidth = $derived(Number.isFinite(strokeWidth) ? Math.min(${cutout.maxWidth}, Math.max(${cutout.minWidth}, strokeWidth)) : ${cutout.defaultWidth});
  const cutoutPath = $derived(${JSON.stringify(cutout.outerPath)} + ' M ${cutout.left} ' + (${cutout.centerY} - gapWidth / 2) + ' H ${cutout.right} V ' + (${cutout.centerY} + gapWidth / 2) + ' H ${cutout.left} Z');`
    : '';
  const filledBody =
    icon.filled?.root.children
      .map((node) =>
        cutout && node.attrs['data-part'] === cutout.part
          ? `<g data-part=${JSON.stringify(cutout.part)}><path d={cutoutPath}></path></g>`
          : render(node),
      )
      .join('\n  ') ?? '';
  if (icon.filled) {
    files.set(
      `src/lib/filled/${component}.svelte`,
      `<!-- Generated by tools/generate.ts. Do not edit. -->
<script lang="ts">
  import type { FilledIconProps } from '../props.js';
  let { size = 24, color = 'currentColor', strokeWidth = ${cutout?.defaultWidth ?? STROKE_WEIGHTS.regular}, label, class: className }: FilledIconProps = $props();${gapScript}
</script>
<svg ${filledRootAttrs}${cutout ? ' data-cutout-width={gapWidth}' : ''}>
  ${filledBody}
</svg>\n`,
    );
    filledIndex += `export { default as ${component} } from './${component}.svelte';\n`;
    exports[`./filled/${icon.name}`] = {
      types: `./dist/filled/${component}.svelte.d.ts`,
      svelte: `./dist/filled/${component}.svelte`,
      default: `./dist/filled/${component}.svelte`,
    };
  }
  const variantAttrs = icon.filled
    ? rootAttrs.replace(
        'fill="none" stroke={color} stroke-width={strokeWidth}',
        `fill={iconStyle === 'filled' ? color : 'none'} stroke={iconStyle === 'filled' ? 'none' : color} stroke-width={iconStyle === 'filled' ? undefined : strokeWidth} fill-rule={iconStyle === 'filled' ? 'evenodd' : undefined}`,
      )
    : rootAttrs;
  files.set(
    `src/lib/${component}.svelte`,
    `<!-- Generated by tools/generate.ts. Do not edit. -->
<script lang="ts">
  import type { IconProps } from './props.js';
  let { ${iconProps}, style: iconStyle = 'outline' }: ${icon.filled ? 'IconProps' : "Omit<IconProps, 'style'> & { style?: 'outline' }"} = $props();${gapScript}
</script>
<svg ${variantAttrs}${cutout ? " data-cutout-width={iconStyle === 'filled' ? gapWidth : undefined}" : ''}>
  ${icon.filled ? `{#if iconStyle === 'filled'}\n${filledBody}\n{:else}\n${body}\n{/if}` : body}
</svg>
`,
  );
}
files.set('src/lib/index.ts', staticIndex);
files.set('src/lib/filled/index.ts', filledIndex);
exports['./filled'] = {
  types: './dist/filled/index.d.ts',
  svelte: './dist/filled/index.js',
  default: './dist/filled/index.js',
};
files.set(
  'src/lib/catalog.json',
  JSON.stringify(
    {
      generatedBy: 'tools/generate.ts',
      strokeWeights: STROKE_WEIGHTS,
      icons: icons.map((icon) => ({
        ...icon.metadata,
        styles: icon.filled ? ['outline', 'filled'] : ['outline'],
        defaultStrokeWidth: Number(icon.root.attrs['stroke-width']),
        filledDefaultStrokeWidth: icon.filled?.cutout?.defaultWidth ?? null,
        reviewStatus: icon.metadata.review?.status ?? 'draft',
      })),
    },
    null,
    2,
  ) + '\n',
);
exports['./catalog.json'] = './dist/catalog.json';
const packagePath = 'package.json';
const manifest = JSON.parse(await readFile(resolve(root, packagePath), 'utf8'));
manifest.exports = exports;
files.set(packagePath, JSON.stringify(manifest, null, 2) + '\n');
const formatting = await resolveConfig(resolve(root, '.prettierrc.json'));
for (const [path, source] of files) {
  const destination = resolve(root, path);
  const content = await format(source, { ...formatting, filepath: destination });
  if (check) {
    if ((await readFile(destination, 'utf8').catch(() => '')) !== content)
      throw new Error(`Generated output is stale: ${path}`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
// Removed icons must not leave stale, importable generated components behind.
async function scan(directory: string): Promise<string[]> {
  const entries = await readdir(resolve(root, directory), { withFileTypes: true }).catch(() => []);
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory() ? scan(`${directory}/${entry.name}`) : [`${directory}/${entry.name}`],
      ),
    )
  ).flat();
}
for (const path of await scan('src/lib')) {
  const content = await readFile(resolve(root, path), 'utf8');
  if (content.includes('Generated by tools/generate.ts.') && !files.has(path))
    throw new Error(`Stale generated file: ${path}; remove it explicitly`);
}
console.log(`${check ? 'Verified' : 'Generated'} ${files.size} deterministic outputs.`);
