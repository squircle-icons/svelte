import { STROKE_WEIGHTS } from '@squircle-icons/core/source/types';
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { root } from './paths.js';
import { componentNames } from './icon-names.js';
import { fileURLToPath } from 'node:url';
import type { CoreIcon } from '@squircle-icons/core/catalog-types';
type SvgNode = CoreIcon['root'];

const check = process.argv.includes('--check');
const header = '// Generated by tools/generate.ts. Do not edit.\n';
const files = new Map<string, string>();
const sourceIcons: CoreIcon[] = JSON.parse(
  await readFile(fileURLToPath(import.meta.resolve('@squircle-icons/core/catalog.json')), 'utf8'),
);
const icons = sourceIcons;
const names = componentNames(icons.map((icon) => icon.name));
const render = (node: SvgNode, adjustable: boolean): string => {
  const attrs = Object.entries(node.attrs)
    .map(([key, value]) =>
      key === 'stroke-width' && adjustable
        ? 'stroke-width={resolvedStrokeWidth}'
        : `${key}=${JSON.stringify(value)}`,
    )
    .join(' ');
  return `<${node.tag}${attrs ? ' ' + attrs : ''}>${node.children.map((child) => render(child, adjustable)).join('')}</${node.tag}>`;
};
const exports: Record<string, unknown> = {
  '.': { types: './dist/index.d.ts', svelte: './dist/index.js', default: './dist/index.js' },
};
let staticIndex =
  header + "export type { IconProps, IconStyle, IconStrokeWidth } from './props.js';\n";
for (const [index, icon] of icons.entries()) {
  const component = names[index];
  const hasMotion = icon.name === 'trash';
  const propsType = hasMotion
    ? "ComponentProps<typeof TrashMotion> & ({ animate: true; strokeWidth?: never } | { animate?: false; strokeWidth?: IconProps['strokeWidth'] })"
    : icon.adjustableStroke
      ? 'IconProps'
      : "Omit<IconProps, 'strokeWidth'>";
  staticIndex += `export { default as ${component} } from './${component}.svelte';\n`;
  exports[`./${icon.name}`] = {
    types: `./dist/${component}.svelte.d.ts`,
    svelte: `./dist/${component}.svelte`,
    default: `./dist/${component}.svelte`,
  };
  const outline = icon.root.children
    .map((child) => render(child, icon.adjustableStroke))
    .join('\n');
  const filled = icon.filled!.root.children.map((child) => render(child, false)).join('\n');
  files.set(
    `src/lib/${component}.svelte`,
    `<!-- Generated by tools/generate.ts. Do not edit. -->
<script lang="ts">
  import type { IconProps } from './props.js';${hasMotion ? "\n  import type { ComponentProps } from 'svelte';\n  import TrashMotion from './motion/TrashMotion.svelte';" : ''}
  ${icon.adjustableStroke ? "import { resolveStrokeWidth } from './stroke-width.js';" : ''}
  let { size = 24, color = 'currentColor', ${icon.adjustableStroke ? "strokeWidth = 'regular', " : ''}label, class: className, style: iconStyle = 'outline'${hasMotion ? ', animate = false, open = false, progress, speed = 1, onprogress, onsettle' : ''} }: ${propsType} = $props();
  const accessibleLabel = $derived(label?.trim());
  ${icon.adjustableStroke ? 'const resolvedStrokeWidth = $derived(resolveStrokeWidth(strokeWidth));' : ''}
</script>
${hasMotion ? '{#if animate}\n<TrashMotion {open} {progress} {speed} {size} {color} style={iconStyle} {label} class={className} {onprogress} {onsettle} />\n{:else}\n' : ''}<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width={size} height={size} color={color} fill="none" stroke="none" overflow="hidden" class={className} role={accessibleLabel ? 'img' : undefined} aria-label={accessibleLabel || undefined} aria-hidden={accessibleLabel ? undefined : true} focusable="false" data-frame="none" data-source="figma-current"${icon.adjustableStroke ? " stroke-width={iconStyle === 'outline' ? resolvedStrokeWidth : undefined}" : ''}>
{#if iconStyle === 'filled'}
${filled}
{:else}
${outline}
{/if}
</svg>
${hasMotion ? '{/if}\n' : ''}`,
  );
}
files.set(
  'src/lib/stroke-width.ts',
  header +
    `import type { IconStrokeWidth } from './props.js';
const weights = ${JSON.stringify(STROKE_WEIGHTS)} as const;
export function resolveStrokeWidth(value: IconStrokeWidth): number {
  if (typeof value === 'number' && Number.isFinite(value) && value >= 0) return value;
  return value === 'thin' ? weights.thin : value === 'bold' ? weights.bold : weights.regular;
}
`,
);
files.set('src/lib/index.ts', staticIndex);
files.set(
  'src/lib/catalog.json',
  JSON.stringify(
    {
      generatedBy: 'tools/generate.ts',
      strokeWeights: STROKE_WEIGHTS,
      icons: icons.map((icon) => ({
        ...icon.metadata,
        label: icon.label,
        group: icon.group,
        baseIcon: icon.name,
        frame: 'none',
        styles: ['outline', 'filled'],
        frames: [],
        defaultStrokeWidth: icon.baseStroke,
        filledDefaultStrokeWidth: null,
        adjustableStroke: icon.adjustableStroke,
        figma: icon.figma,
        reviewStatus: icon.metadata.review?.status ?? 'draft',
      })),
    },
    null,
    2,
  ) + '\n',
);
exports['./catalog.json'] = './dist/catalog.json';
const figmaCatalog = fileURLToPath(
  import.meta.resolve('@squircle-icons/core/design/figma-catalog'),
);
files.set('src/lib/design/figma-catalog.js', header + (await readFile(figmaCatalog, 'utf8')));
files.set(
  'src/lib/design/figma-catalog.d.ts',
  header + (await readFile(figmaCatalog.replace(/\.js$/, '.d.ts'), 'utf8')),
);
exports['./design/figma-catalog'] = {
  types: './dist/design/figma-catalog.d.ts',
  default: './dist/design/figma-catalog.js',
};
// Preserve relative imports for shared pure geometry used by opt-in morphs.
const strokes = fileURLToPath(import.meta.resolve('@squircle-icons/core/morph/round-strokes'));
files.set('src/lib/morph/round-strokes.js', header + (await readFile(strokes, 'utf8')));
files.set(
  'src/lib/morph/round-strokes.d.ts',
  header + (await readFile(strokes.replace(/\.js$/, '.d.ts'), 'utf8')),
);
// Pair implementations stay opt-in; static imports never traverse these modules.
for (const [family, pair, component, type] of [
  ['morph', 'sun-moon', 'SunMoonMorph', 'SunMoonGeometry'],
  ['morph', 'plus-x', 'PlusXMorph', 'PlusXGeometry'],
  ['morph', 'menu-x', 'MenuXMorph', 'MenuXGeometry'],
  ['morph', 'plus-minus', 'PlusMinusMorph', 'PlusMinusGeometry'],
  ['motion', 'trash', 'TrashMotion', 'TrashGeometry'],
  ['morph', 'maximize-minimize', 'MaximizeMinimizeMorph', 'MaximizeMinimizeGeometry'],
]) {
  exports[`./${family}/${pair}`] = {
    types: `./dist/${family}/${component}.svelte.d.ts`,
    svelte: `./dist/${family}/${component}.svelte`,
    default: `./dist/${family}/${component}.svelte`,
  };
  const implementation = fileURLToPath(
    import.meta.resolve(`@squircle-icons/core/${family}/${pair}`),
  );
  files.set(
    `src/lib/${family}/${pair}-geometry.js`,
    header + (await readFile(implementation, 'utf8')),
  );
  files.set(
    `src/lib/${family}/${pair}-geometry.d.ts`,
    header + (await readFile(implementation.replace(/\.js$/, '.d.ts'), 'utf8')),
  );
  files.set(
    `src/lib/${family}/${pair}-data.js`,
    header +
      'export default ' +
      (await readFile(
        fileURLToPath(import.meta.resolve(`@squircle-icons/core/${family}/${pair}.json`)),
        'utf8',
      )) +
      ';\n',
  );
  files.set(
    `src/lib/${family}/${pair}-data.d.ts`,
    header +
      `import type { ${type} } from './${pair}-geometry.js';\ndeclare const geometry: ${type};\nexport default geometry;\n`,
  );
}
const packagePath = 'package.json';
const manifest = JSON.parse(await readFile(resolve(root, packagePath), 'utf8'));
manifest.exports = exports;
files.set(packagePath, JSON.stringify(manifest, null, 2) + '\n');
const formatting = await resolveConfig(resolve(root, '.prettierrc.json'));
for (const [path, source] of files) {
  const destination = resolve(root, path);
  const content = await format(source, { ...formatting, filepath: destination });
  if (check) {
    if ((await readFile(destination, 'utf8').catch(() => '')) !== content)
      throw new Error(`Generated output is stale: ${path}`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
// Removed icons must not leave stale, importable generated components behind.
async function scan(directory: string): Promise<string[]> {
  const entries = await readdir(resolve(root, directory), { withFileTypes: true }).catch(() => []);
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory() ? scan(`${directory}/${entry.name}`) : [`${directory}/${entry.name}`],
      ),
    )
  ).flat();
}
for (const path of await scan('src/lib')) {
  const content = await readFile(resolve(root, path), 'utf8');
  if (content.includes('Generated by tools/generate.ts.') && !files.has(path))
    throw new Error(`Stale generated file: ${path}; remove it explicitly`);
}
console.log(`${check ? 'Verified' : 'Generated'} ${files.size} deterministic outputs.`);
